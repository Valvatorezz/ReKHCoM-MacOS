"""Keep browser card metadata in sync with the launcher's generated table."""
from pathlib import Path
import re,json
ROOT=Path(__file__).resolve().parents[2]
s=(ROOT/'port/decompui/card_table.h').read_text()
cards=re.findall(r'\{\s*(\d+),\s*(0x[0-9a-fA-F]+),\s*(\d+),\s*(\d+),\s*(\d+),\s*\{\s*(-?\d+),\s*(-?\d+),\s*(-?\d+)\s*\}\s*\}',s)
spr=s.split('static const Sprite')[1].split('};')[0]
sprites=[]
for a,b in re.findall(r'\{\s*\{([^{}]+)\},\s*\{([^{}]+)\}\s*\}',spr):
    sprites.append([[int(x.strip(),0) for x in a.split(',')],[int(x.strip(),0) for x in b.split(',')]])
def names(label):return re.findall(r'"([^"\n]*)"',s.split(label)[1].split('};')[0])
obj={'cards':[[int(v,0) if v.startswith('0x') else int(v) for v in c] for c in cards], 'sprites':sprites,'kinds':names('kKindNames[kKindCount]'),'maps':names('kMapGroupNames[kMapGroupCount]')}
assert len(obj['cards'])==950 and len(sprites)==136
(ROOT/'port/web/cards.js').write_text('/* Generated by gen_web_cards.py. Metadata only, no cartridge pixels. */\nconst ReKHCards='+json.dumps(obj,separators=(',',':'))+';\n')
